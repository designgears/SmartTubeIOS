/// Full-screen native player: `AVPlayerViewController` driving `PlaybackViewModel.player`
/// (so every stream fallback/decipher path still applies), with YouTube features exposed
/// through native transport-bar menus, contextual actions and info panels.
struct TVPlayerScreen: View {
    let video: Video

    @Environment(\.innerTubeAPI) private var api
    @Environment(SettingsStore.self) private var store
    @Environment(AuthService.self) private var auth
    @Environment(TVNavigator.self) private var navigator
    @Environment(\.scenePhase) private var scenePhase
    @State private var vm: PlaybackViewModel?
    @State private var transportBar = TVPlayerPresentationState()

    var body: some View {
        ZStack {
            Color.black.ignoresSafeArea()
            if let vm {
                TVNativePlayer(
                    vm: vm, state: menuState(vm), actions: actions(vm), fallbackVideo: video,
                    fillsScreen: store.settings.videoGravityMode == .fill,
                    segments: vm.sponsorSegments, duration: vm.duration, liveColor: AppColor.live(store),
                    isLive: vm.isLive,
                    transportBar: transportBar
                )
                .ignoresSafeArea()
                TVPlayerOverlays(vm: vm, video: video, isVideoOnScreen: transportBar.isVideoOnScreen) {
                    navigator.nowPlaying = nil
                }
            }
        }
        .onAppear(perform: start)
        .onDisappear { vm?.stop() }
        // Account switch: stop now, while the previous account is live, so its progress
        // and watch time are saved to it; then close.
        .onReceive(NotificationCenter.default.publisher(for: AccountScope.willChangeNotification)) { _ in
            vm?.stop()
            navigator.nowPlaying = nil
        }
        // `videoEnded` is only set when nothing plays next (autoplay off, or the queue and
        // suggestions are exhausted) — return to the menus instead of sitting on the last frame.
        .onChange(of: vm?.videoEnded ?? false) { _, ended in
            if ended { navigator.nowPlaying = nil }
        }
        .onChange(of: scenePhase) { _, phase in
            switch phase {
            case .background: vm?.handleBackground()
            case .active: vm?.handleForeground()
            default: break
            }
        }
    }

    private func start() {
        guard vm == nil else { return }
        let model = PlaybackViewModel(api: api)
        model.updateSettings(store.settings)
        model.updateAuthToken(auth.accessToken)
        model.load(video: video)  // applies this channel's remembered speed (1× for music)
        vm = model
    }

    private func menuState(_ vm: PlaybackViewModel) -> TVPlayerMenuState {
        TVPlayerMenuState(
            formats: vm.availableFormats,
            selectedFormatID: vm.selectedFormat?.id,
            captions: vm.availableCaptions.map {
                TVPlayerMenuState.CaptionOption(id: $0.id, name: $0.isAutoGenerated ? "\($0.name) (auto)" : $0.name)
            },
            selectedCaptionID: vm.selectedCaption?.id,
            speed: vm.currentPlaybackSpeed,
            isLiked: vm.likeStatus == .like,
            isDisliked: vm.likeStatus == .dislike,
            chapters: vm.chapters.map { TVPlayerMenuState.ChapterOption(title: $0.title, start: $0.startTime) },
            hasNext: vm.hasNext,
            hasPrevious: vm.hasPrevious,
            skipLabel: vm.currentToastSegment.map { "Skip \($0.category.tvLabel)" },
            hasChannel: (vm.currentVideo ?? video).channelId != nil,
            subtitle: Self.subtitle(vm: vm, fallback: video),
            platform: (vm.currentVideo ?? video).platform
        )
    }

    /// Channel, views and age: what's known from the card, refined by the watch page. Live:
    /// "Channel · 5.3K watching" (AVKit puts its own red LIVE tag in front of it).
    static func subtitle(vm: PlaybackViewModel, fallback: Video) -> String {
        let video = vm.currentVideo ?? fallback
        let details = vm.videoDetails
        var parts: [String] = []
        // A deep-linked video starts without title or channel; the player response has them.
        if let channel = video.channelTitle.nilIfEmpty ?? vm.playerInfo?.video.channelTitle.nilIfEmpty {
            parts.append(channel)
        }
        if vm.isLive {
            if let watching = vm.watchingCount { parts.append("\(compactCount(watching)) watching") }
            return parts.joined(separator: " · ")
        }
        if let views = vm.viewCount ?? video.viewCount {
            parts.append("\(compactCount(views)) views")
        }
        if let age = details?.relativeDateText ?? video.publishedTimeText ?? details?.dateText, !age.isEmpty {
            parts.append(age)
        }
        return parts.joined(separator: " · ")
    }

    private func actions(_ vm: PlaybackViewModel) -> TVPlayerActions {
        let store = store
        let navigator = navigator
        let fallback = video
        return TVPlayerActions(
            selectFormat: { vm.selectFormat($0) },
            selectCaption: { id in vm.selectCaption(id.flatMap { id in vm.availableCaptions.first { $0.id == id } }) },
            setSpeed: { speed in
                switch vm.userSelectedPlaybackSpeed(speed) {
                case .channel(let channelId): store.settings.channelPlaybackSpeeds[channelId] = speed
                case .global: store.settings.playbackSpeed = speed
                case .sessionOnly: break  // music: never remembered
                }
            },
            like: { vm.like() },
            dislike: { vm.dislike() },
            skipSegment: { vm.skipToastSegment() },
            next: { vm.playNext() },
            previous: { vm.playPrevious() },
            seek: { vm.seek(to: $0) },
            playVideo: { vm.load(video: $0) },
            openChannel: { navigator.openChannel(of: vm.currentVideo ?? fallback) }
        )
    }
}

// MARK: - Menu state / actions

/// Value snapshot of everything the transport-bar menus show. Menus are rebuilt only when
/// this changes (it deliberately excludes the playback clock).
struct TVPlayerMenuState: Equatable {
    struct CaptionOption: Equatable {
        let id: String
        let name: String
    }
    struct ChapterOption: Equatable {
        let title: String
        let start: TimeInterval
    }

    var formats: [VideoFormat]
    var selectedFormatID: UUID?
    var captions: [CaptionOption]
    var selectedCaptionID: String?
    var speed: Double
    var isLiked: Bool
    var isDisliked: Bool
    var chapters: [ChapterOption]
    var hasNext: Bool
    var hasPrevious: Bool
    var skipLabel: String?
    var hasChannel: Bool
    /// "Channel · 1.5M views · 9 hours ago" — the line under the title in the transport bar.
    var subtitle: String
    /// Twitch and Kick have no likes, and no YouTube formats to pick from.
    var platform: StreamPlatform = .youtube
}

struct TVPlayerActions {
    var selectFormat: (VideoFormat?) -> Void
    var selectCaption: (String?) -> Void
    var setSpeed: (Double) -> Void
    var like: () -> Void
    var dislike: () -> Void
    var skipSegment: () -> Void
    var next: () -> Void
    var previous: () -> Void
    var seek: (TimeInterval) -> Void
    var playVideo: (Video) -> Void
    var openChannel: () -> Void
}

// MARK: - AVPlayerViewController bridge

struct TVNativePlayer: UIViewControllerRepresentable {
    let vm: PlaybackViewModel
    let state: TVPlayerMenuState
    let actions: TVPlayerActions
    let fallbackVideo: Video
    /// Settings › Video Fit: crop to fill instead of letterboxing.
    var fillsScreen = false
    /// SponsorBlock segments for the strip on the scrubber.
    var segments: [SponsorSegment] = []
    var duration: TimeInterval = 0
    /// Settings › Colors › Live, for AVKit's own LIVE tags.
    var liveColor: Color
    /// Live streams keep the TV's display mode (see `matchesDisplayMode`).
    var isLive = false
    /// What the player is showing, for the overlays drawn on top of it.
    var transportBar: TVPlayerPresentationState?

    func makeCoordinator() -> Coordinator { Coordinator() }

    /// Videos switch the TV to their frame rate and dynamic range. Live streams don't: a live
    /// ladder can change frame rate mid-stream, and each switch stalls the picture while the
    /// audio carries on.
    static func matchesDisplayMode(isLive: Bool) -> Bool { !isLive }

    func makeUIViewController(context: Context) -> AVPlayerViewController {
        let pvc = AVPlayerViewController()
        pvc.player = vm.player
        // Speed is offered through our own menu so it persists in settings.
        pvc.speeds = []
        // Match the TV's frame rate / dynamic range to the content.
        pvc.appliesPreferredDisplayCriteriaAutomatically = Self.matchesDisplayMode(isLive: isLive)
        pvc.videoGravity = fillsScreen ? .resizeAspectFill : .resizeAspect
        context.coordinator.transportBar = transportBar
        pvc.delegate = context.coordinator
        context.coordinator.attach(pvc, vm: vm, fallbackVideo: fallbackVideo, actions: actions)
        context.coordinator.apply(state: state)
        context.coordinator.liveBadgeTint.color = UIColor(liveColor)
        context.coordinator.updateSegmentStrip(segments: segments, duration: duration)
        return pvc
    }

    func updateUIViewController(_ pvc: AVPlayerViewController, context: Context) {
        context.coordinator.actions = actions
        context.coordinator.apply(state: state)
        let gravity: AVLayerVideoGravity = fillsScreen ? .resizeAspectFill : .resizeAspect
        if pvc.videoGravity != gravity { pvc.videoGravity = gravity }
        let matching = Self.matchesDisplayMode(isLive: isLive)
        if pvc.appliesPreferredDisplayCriteriaAutomatically != matching {
            pvc.appliesPreferredDisplayCriteriaAutomatically = matching
        }
        context.coordinator.liveBadgeTint.color = UIColor(liveColor)
        context.coordinator.updateSegmentStrip(segments: segments, duration: duration)
    }

    static func dismantleUIViewController(_ pvc: AVPlayerViewController, coordinator: Coordinator) {
        coordinator.detach()
    }

    @MainActor
    final class Coordinator: NSObject, AVPlayerViewControllerDelegate, UIGestureRecognizerDelegate {
        var actions: TVPlayerActions?
        var transportBar: TVPlayerPresentationState?
        private weak var pvc: AVPlayerViewController?
        weak var vm: PlaybackViewModel?
        private var fallbackVideo: Video?
        private var lastState: TVPlayerMenuState?
        private var itemObservation: NSKeyValueObservation?
        private var readyObservation: NSKeyValueObservation?
        private var playingObservation: NSKeyValueObservation?
        /// The current video has been shown; stays set through later buffering pauses.
        private var videoShown = false
        /// Which video `videoShown` is for: a quality change or retry replaces the item of the
        /// same video and must not bring the backdrop back.
        private var shownVideoId: String?
        private var pausedStartFallback: Task<Void, Never>?
        private var artworkTask: Task<Void, Never>?
        private var panelsShowChapters: Bool?
        /// What Auto is playing ("1080p"), from the decoded picture size; shown on Auto.
        private var autoQuality: String?
        private var presentationObservation: NSKeyValueObservation?
        /// SponsorBlock segments, inside the native transport bar (TVTransportBarTracking.swift).
        let segmentStrip = TVSponsorSegmentStrip()
        /// AVKit's LIVE tags in the app's live color (TVLiveBadgeTint.swift).
        let liveBadgeTint = TVLiveBadgeTint()
        var playerView: UIView? { pvc?.view }

        func attach(
            _ pvc: AVPlayerViewController, vm: PlaybackViewModel, fallbackVideo: Video, actions: TVPlayerActions
        ) {
            self.pvc = pvc
            self.vm = vm
            self.fallbackVideo = fallbackVideo
            self.actions = actions
            itemObservation = vm.player.observe(\.currentItem, options: [.initial, .new]) { [weak self] player, _ in
                let hasItem = player.currentItem != nil
                Task { @MainActor in
                    self?.applyMetadata()
                    // A new video (autoplay, Up Next): back to the loading backdrop until it shows.
                    if hasItem { self?.videoWillChange() }
                }
            }
            installSegmentStrip(on: pvc.view)
            presentationObservation = observePictureSize(of: vm.player)
            readyObservation = pvc.observe(\.isReadyForDisplay, options: [.initial, .new]) { [weak self] _, _ in
                Task { @MainActor in self?.refreshVideoOnScreen() }
            }
            playingObservation = vm.player.observe(\.timeControlStatus, options: [.new]) { [weak self] _, _ in
                Task { @MainActor in self?.refreshVideoOnScreen() }
            }
        }

        // MARK: Loading backdrop

        /// The backdrop leaves once the picture is on screen *and* playing — a ready first frame
        /// alone can be the frame before a resume seek. A video that starts paused still clears
        /// it shortly after its first frame.
        private func refreshVideoOnScreen() {
            guard let pvc, let vm else { return }
            if !videoShown, pvc.isReadyForDisplay {
                if vm.player.timeControlStatus == .playing {
                    videoShown = true
                    shownVideoId = vm.currentVideo?.id
                } else if pausedStartFallback == nil {
                    pausedStartFallback = Task { [weak self] in
                        try? await Task.sleep(for: .seconds(2))
                        guard !Task.isCancelled, let self, self.pvc?.isReadyForDisplay == true else { return }
                        self.videoShown = true
                        self.shownVideoId = self.vm?.currentVideo?.id
                        self.publishVideoOnScreen()
                    }
                }
            }
            publishVideoOnScreen()
        }

        private func videoWillChange() {
            guard vm?.currentVideo?.id != shownVideoId else { return }
            videoShown = false
            pausedStartFallback?.cancel()
            pausedStartFallback = nil
            refreshVideoOnScreen()
        }

        private func publishVideoOnScreen() {
            guard transportBar?.isVideoOnScreen != videoShown else { return }
            withAnimation(.easeOut(duration: 0.3)) { transportBar?.isVideoOnScreen = videoShown }
        }

        // MARK: Transport bar

        /// Observe only — never compete with AVPlayerViewController's own recognizers.
        nonisolated func gestureRecognizer(
            _ gestureRecognizer: UIGestureRecognizer,
            shouldRecognizeSimultaneouslyWith otherGestureRecognizer: UIGestureRecognizer
        ) -> Bool { true }

        nonisolated func playerViewController(
            _ playerViewController: AVPlayerViewController,
            willTransitionToVisibilityOfTransportBar visible: Bool,
            with coordinator: any AVPlayerViewControllerAnimationCoordinator
        ) {
            MainActor.assumeIsolated {
                tvPlayerLog.debug("[transportBar] visible=\(visible)")
                attachSegmentStrip()
            }
            coordinator.addCoordinatedAnimations(nil) { [weak self] _ in
                Task { @MainActor in self?.attachSegmentStrip() }
            }
        }

        private func observePictureSize(of player: AVPlayer) -> NSKeyValueObservation {
            player.observe(\.currentItem?.presentationSize, options: [.initial, .new]) { [weak self] player, _ in
                let size = player.currentItem?.presentationSize ?? .zero
                Task { @MainActor in self?.showAutoQuality(qualityName(width: size.width, height: size.height)) }
            }
        }

        /// Retitles Auto when the picture Auto chose changes (ABR switching quality).
        private func showAutoQuality(_ name: String?) {
            guard name != autoQuality else { return }
            autoQuality = name
            guard let pvc, let state = lastState, state.selectedFormatID == nil else { return }
            pvc.transportBarCustomMenuItems = menus(for: state)
        }

        func detach() {
            presentationObservation?.invalidate()
            itemObservation?.invalidate()
            itemObservation = nil
            readyObservation?.invalidate()
            readyObservation = nil
            playingObservation?.invalidate()
            playingObservation = nil
            pausedStartFallback?.cancel()
            artworkTask?.cancel()
            segmentStrip.removeFromSuperview()
        }

        func apply(state: TVPlayerMenuState) {
            guard let pvc, state != lastState else { return }
            let previous = lastState
            lastState = state
            // Replacing the menus closes or resets one that is open, so only rebuild them when
            // something they show changed — not when the SponsorBlock skip button comes and goes.
            var menuState = state
            menuState.skipLabel = nil
            var previousMenuState = previous
            previousMenuState?.skipLabel = nil
            if menuState != previousMenuState {
                pvc.transportBarCustomMenuItems = menus(for: state)
            }
            if state.skipLabel != previous?.skipLabel {
                if let label = state.skipLabel {
                    pvc.contextualActions = [
                        UIAction(title: label, image: UIImage(systemName: AppSymbol.nextTrack)) { [weak self] _ in
                            self?.actions?.skipSegment()
                        }
                    ]
                } else {
                    pvc.contextualActions = []
                }
            }
            if state.subtitle != previous?.subtitle { applyMetadata() }
            let showChapters = !state.chapters.isEmpty
            if panelsShowChapters != showChapters {
                panelsShowChapters = showChapters
                installPanels(showChapters: showChapters)
            }
        }

        // MARK: Info panels (swipe down)

        private func installPanels(showChapters: Bool) {
            guard let pvc, let vm else { return }
            let upNext = UIHostingController(
                rootView: TVUpNextPanel(vm: vm) { [weak self] video in self?.actions?.playVideo(video) })
            upNext.title = "Up Next"
            upNext.preferredContentSize = CGSize(width: 0, height: 400)
            let details = UIHostingController(rootView: TVDetailsPanel(vm: vm, fallback: fallbackVideo))
            details.title = "Details"
            details.preferredContentSize = CGSize(width: 0, height: 400)
            var panels: [UIViewController] = [details, upNext]
            if showChapters {
                let chapters = UIHostingController(
                    rootView: TVChaptersPanel(vm: vm) { [weak self] start in self?.actions?.seek(start) })
                chapters.title = "Chapters"
                chapters.preferredContentSize = CGSize(width: 0, height: 400)
                panels.append(chapters)
            }
            pvc.customInfoViewControllers = panels
        }

        // MARK: Transport-bar menus

        /// Auto (with what it's playing) and each distinct quality, best first.
        private func qualityMenu(for state: TVPlayerMenuState) -> UIMenu {
            var qualityChildren: [UIMenuElement] = [
                UIAction(
                    title: state.selectedFormatID == nil ? autoQuality.map { "Auto (\($0))" } ?? "Auto" : "Auto",
                    state: state.selectedFormatID == nil ? .on : .off
                ) { [weak self] _ in
                    self?.actions?.selectFormat(nil)
                }
            ]
            var seen = Set<String>()
            for format in state.formats.sorted(by: { ($0.height, $0.fps) > ($1.height, $1.fps) }) {
                let key = "\(format.qualityLabel)|\(format.codecShortLabel)"
                guard format.height > 0, seen.insert(key).inserted else { continue }
                let action = UIAction(
                    title: format.qualityLabel,
                    state: format.id == state.selectedFormatID ? .on : .off
                ) { [weak self] _ in self?.actions?.selectFormat(format) }
                action.subtitle = format.codecShortLabel
                qualityChildren.append(action)
            }
            return UIMenu(
                title: "Quality", image: UIImage(systemName: AppSymbol.quality),
                options: .singleSelection, children: qualityChildren)
        }

        private func menus(for state: TVPlayerMenuState) -> [UIMenuElement] {
            var items: [UIMenuElement] = []
            let isYouTube = state.platform == .youtube

            if isYouTube {
                items.append(
                    UIAction(
                        title: state.isLiked ? "Liked" : "Like",
                        image: UIImage(systemName: state.isLiked ? AppSymbol.thumbsUpFill : AppSymbol.thumbsUp)
                    ) { [weak self] _ in self?.actions?.like() })
                items.append(qualityMenu(for: state))
            }

            if !state.captions.isEmpty {
                var children: [UIMenuElement] = [
                    UIAction(title: "Off", state: state.selectedCaptionID == nil ? .on : .off) { [weak self] _ in
                        self?.actions?.selectCaption(nil)
                    }
                ]
                children += state.captions.map { option in
                    UIAction(
                        title: option.name, state: option.id == state.selectedCaptionID ? .on : .off,
                        handler: { [weak self] _ in self?.actions?.selectCaption(option.id) })
                }
                items.append(
                    UIMenu(
                        title: "Subtitles", image: UIImage(systemName: AppSymbol.subtitles),
                        options: .singleSelection, children: children))
            }

            let speeds: [Double] = [0.5, 0.75, 1, 1.25, 1.5, 1.75, 2]
            items.append(
                UIMenu(
                    title: "Speed", image: UIImage(systemName: AppSymbol.speed),
                    options: .singleSelection,
                    children: speeds.map { speed in
                        UIAction(
                            title: Self.speedLabel(speed), state: abs(speed - state.speed) < 0.01 ? .on : .off,
                            handler: { [weak self] _ in self?.actions?.setSpeed(speed) })
                    }))

            if !state.chapters.isEmpty {
                items.append(
                    UIMenu(
                        title: "Chapters", image: UIImage(systemName: AppSymbol.chapters),
                        children: state.chapters.map { chapter in
                            let action = UIAction(title: chapter.title) { [weak self] _ in
                                self?.actions?.seek(chapter.start)
                            }
                            action.subtitle = Self.timeLabel(chapter.start)
                            return action
                        }))
            }

            var more: [UIMenuElement] = []
            if isYouTube {
                more.append(
                    UIAction(
                        title: state.isDisliked ? "Disliked" : "Dislike",
                        image: UIImage(systemName: state.isDisliked ? AppSymbol.thumbsDownFill : AppSymbol.thumbsDown)
                    ) { [weak self] _ in self?.actions?.dislike() })
            }
            if state.hasPrevious {
                more.append(
                    UIAction(
                        title: "Previous Video", image: UIImage(systemName: AppSymbol.previousTrack),
                        handler: { [weak self] _ in self?.actions?.previous() }))
            }
            if state.hasNext {
                more.append(
                    UIAction(
                        title: "Next Video", image: UIImage(systemName: AppSymbol.nextTrack),
                        handler: { [weak self] _ in self?.actions?.next() }))
            }
            if state.hasChannel {
                more.append(
                    UIAction(
                        title: "Go to Channel", image: UIImage(systemName: AppSymbol.personSquare),
                        handler: { [weak self] _ in self?.actions?.openChannel() }))
            }
            if !more.isEmpty {
                items.append(UIMenu(title: "More", image: UIImage(systemName: AppSymbol.more), children: more))
            }
            return items
        }

        // MARK: Metadata (native Info panel)

        private func applyMetadata() {
            guard let vm, let item = vm.player.currentItem else { return }
            guard let video = vm.currentVideo ?? fallbackVideo else { return }
            let title = video.title.nilIfEmpty ?? vm.playerInfo?.video.title ?? ""
            var base: [AVMetadataItem] = [Self.metadata(.commonIdentifierTitle, title as NSString)]
            let subtitle = lastState?.subtitle.nilIfEmpty ?? video.channelTitle
            if !subtitle.isEmpty {
                base.append(Self.metadata(.iTunesMetadataTrackSubTitle, subtitle as NSString))
            }
            let description = (vm.playerInfo?.video.description ?? video.description) ?? ""
            if !description.isEmpty {
                base.append(Self.metadata(.commonIdentifierDescription, description as NSString))
            }
            item.externalMetadata = base

            artworkTask?.cancel()
            guard let url = video.highResThumbnailFallbackURLs.first ?? video.thumbnailURL else { return }
            artworkTask = Task { [weak item] in
                guard let (data, _) = try? await URLSession.shared.data(from: url), !Task.isCancelled,
                    let item
                else { return }
                let artwork = AVMutableMetadataItem()
                artwork.identifier = .commonIdentifierArtwork
                artwork.value = data as NSData
                artwork.dataType = kCMMetadataBaseDataType_JPEG as String
                artwork.extendedLanguageTag = "und"
                item.externalMetadata = base + [artwork]
            }
        }

        private static func metadata(_ identifier: AVMetadataIdentifier, _ value: NSString) -> AVMetadataItem {
            let item = AVMutableMetadataItem()
            item.identifier = identifier
            item.value = value
            item.extendedLanguageTag = "und"
            return item
        }

        static func speedLabel(_ speed: Double) -> String {
            speed == 1 ? "Normal" : "\(speed.formatted(.number.precision(.fractionLength(0...2))))×"
        }

        static func timeLabel(_ seconds: TimeInterval) -> String {
            let total = Int(seconds)
            let (hours, minutes, seconds) = (total / 3600, (total % 3600) / 60, total % 60)
            return hours > 0
                ? String(format: "%d:%02d:%02d", hours, minutes, seconds) : String(format: "%d:%02d", minutes, seconds)
        }
    }
}

// MARK: - Overlays

/// Captions, loading and error states drawn above the native player.
struct TVPlayerOverlays: View {
    let vm: PlaybackViewModel
    let video: Video
    let isVideoOnScreen: Bool
    let onClose: () -> Void

    var body: some View {
        ZStack {
            if let cue = vm.currentCaptionCue {
                VStack {
                    Spacer()
                    CaptionCueView(text: cue.text).padding(.bottom, 110)
                }
                .allowsHitTesting(false)
            }
            if vm.error == nil, !isVideoOnScreen {
                loadingBackdrop
                    .allowsHitTesting(false)
                    .transition(.opacity)
            }
            if let error = vm.error {
                TVPlayerErrorPanel(
                    message: error.localizedDescription,
                    onRetry: { vm.retryLoad() },
                    onClose: onClose)
            }
        }
    }

    private var loadingBackdrop: some View {
        let current = vm.currentVideo ?? video
        return ZStack {
            // Blurred, so a small decode is indistinguishable and far cheaper.
            TVRemoteImage(urls: current.highResThumbnailFallbackURLs, pointWidth: 480)
                .blur(radius: 30)
                .overlay(Color.black.opacity(0.55))
                .ignoresSafeArea()
            VStack(spacing: 28) {
                Text(current.title)
                    .font(.title2.weight(.bold))
                    .multilineTextAlignment(.center)
                    .lineLimit(2)
                    .frame(maxWidth: 1200)
                ProgressView().scaleEffect(1.5)
                if let status = vm.retryStatusMessage {
                    Text(status).font(.headline).foregroundStyle(.secondary)
                }
            }
            .foregroundStyle(.white)
        }
    }
}

struct TVPlayerErrorPanel: View {
    let message: String
    let onRetry: () -> Void
    let onClose: () -> Void
    @FocusState private var retryFocused: Bool

    var body: some View {
        ZStack {
            Rectangle().fill(.ultraThinMaterial).ignoresSafeArea()
            VStack(spacing: 32) {
                Image(systemName: AppSymbol.warning)
                    .font(.system(size: 100))
                    .foregroundStyle(.yellow)
                Text("Can't play this video").font(.title.weight(.bold))
                Text(message)
                    .font(.body)
                    .foregroundStyle(.secondary)
                    .multilineTextAlignment(.center)
                    .frame(maxWidth: 1100)
                HStack(spacing: 32) {
